#!/usr/bin/env python3
"""Generate the round display's design assets from design/ into src/display/ui/bettermate/gen/.

    scripts/design/gen_display_assets.py            # everything
    scripts/design/gen_display_assets.py tokens     # one of: tokens icons wordmark fonts

Sources (copied from the BetterMate design system, never edited by hand):
    design/tokens.json                 colors per theme, spacing, radii, sizes
    design/icons/*.svg                 46 pixel glyphs on a 24-unit grid
    design/logos/*-display.png         the wordmark raster for LVGL
    design/fonts/*-Variable.woff2      Space Grotesk and JetBrains Mono

The output is committed, so a firmware build needs none of this tooling. To regenerate you need
Python with fonttools, brotli and Pillow, plus Node for lv_font_conv (override the command with
LV_FONT_CONV, default "npx --yes lv_font_conv@1.5.3").
"""

import json
import os
import re
import shlex
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DESIGN = ROOT / "design"
OUT = ROOT / "src" / "display" / "ui" / "bettermate" / "gen"
BANNER = "// Generated by scripts/design/gen_display_assets.py. Do not edit; change design/ and regenerate.\n"

THEMES = ["light", "dark", "amoled"]

# ---------------------------------------------------------------------------------------------------------
# Tokens
# ---------------------------------------------------------------------------------------------------------


def camel(name):
    parts = re.split(r"[-_.]", name)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def upper_snake(name):
    return re.sub(r"[-.]", "_", name).upper()


def resolve_color(tokens_by_name, name, theme, seen=()):
    """Follow "{alias}" references and theme fallback (a missing theme inherits the first one)."""
    if name in seen:
        raise SystemExit(f"alias loop at color token {name}")
    value = tokens_by_name[name]["value"]
    if isinstance(value, dict):
        value = value.get(theme, value[THEMES[0]])
    alias = re.fullmatch(r"\{([^}]+)\}", value)
    if alias:
        return resolve_color(tokens_by_name, alias.group(1), theme, seen + (name,))
    return value


def gen_tokens():
    tokens = json.loads((DESIGN / "tokens.json").read_text())
    colors = tokens["color"]["tokens"]
    by_name = {t["name"]: t for t in colors}

    fields = []
    for t in colors:
        hexes = [resolve_color(by_name, t["name"], theme) for theme in THEMES]
        # The display has no alpha compositing budget: tokens with an alpha channel (scrim) are web-only.
        if not all(re.fullmatch(r"#[0-9a-fA-F]{6}", h) for h in hexes):
            continue
        fields.append((camel(t["name"]), hexes, t.get("usage", "")))

    lines = [BANNER, "#pragma once\n", "#include <cstdint>\n", "\nnamespace bm::tokens {\n"]
    lines.append("\n// One 0xRRGGBB value per color token; see design/tokens.json for what each one is for.\n")
    lines.append("struct Palette {\n")
    for name, _, _ in fields:
        lines.append(f"    uint32_t {name};\n")
    lines.append("};\n")
    for i, theme in enumerate(THEMES):
        lines.append(f"\ninline constexpr Palette {theme.upper()} = {{\n")
        for name, hexes, _ in fields:
            lines.append(f"    0x{hexes[i][1:].lower()}, // {name}\n")
        lines.append("};\n")

    def px_family(family, comment):
        lines.append(f"\n// {comment}\n")
        for t in tokens[family]["tokens"]:
            m = re.fullmatch(r"(\d+)px", str(t["value"]))
            if not m:
                continue
            # Arduino.h defines DISPLAY as a macro; keep the token source unchanged but avoid that C++ name.
            name = "DISPLAY_SIZE" if t["name"] == "display" else upper_snake(t["name"])
            lines.append(f"inline constexpr int {name} = {m.group(1)};\n")

    px_family("spacing", "Spacing, px (a 4 px grid)")
    px_family("radius", "Corner radii, px (radius-pill is LV_RADIUS_CIRCLE on the display)")
    px_family("size", "Sizes, px")
    px_family("border", "Border widths, px")
    lines.append("\n// Whole-control opacity of a disabled control, 0..255\n")
    for t in tokens["opacity"]["tokens"]:
        lines.append(f"inline constexpr int OPA_{upper_snake(t['name'])} = {round(float(t['value']) * 255)};\n")
    lines.append("\n} // namespace bm::tokens\n")
    (OUT / "bm_tokens.h").write_text("".join(lines))
    print(f"tokens: {len(fields)} colors x {len(THEMES)} themes")


# ---------------------------------------------------------------------------------------------------------
# Icons: 24-unit pixel glyphs -> 1-bit alpha bitmaps at exact 1x, 2x and 3x
# ---------------------------------------------------------------------------------------------------------

RUN = re.compile(r"M(\d+) (\d+)h(\d+)v1H(\d+)z")
GRID = 24
SCALES = [1, 2, 3]


def icon_grid(svg_path):
    svg = svg_path.read_text()
    d = "".join(re.findall(r'\bd="([^"]+)"', svg))
    grid = [[0] * GRID for _ in range(GRID)]
    consumed = 0
    for m in RUN.finditer(d):
        x, y, w, x_back = (int(g) for g in m.groups())
        if x != x_back or x + w > GRID or y >= GRID:
            raise SystemExit(f"{svg_path.name}: run off the 24-unit grid: {m.group(0)}")
        for i in range(w):
            grid[y][x + i] = 1
        consumed += len(m.group(0))
    if consumed != len(d) or consumed == 0:
        raise SystemExit(f"{svg_path.name}: path is not made of whole-pixel runs, refusing to approximate it")
    return grid


def alpha1(grid, scale):
    """Rows padded to a byte, most significant bit first (LV_IMG_CF_ALPHA_1BIT)."""
    size = GRID * scale
    out = bytearray()
    for y in range(size):
        row = grid[y // scale]
        byte = 0
        for x in range(size):
            byte = (byte << 1) | row[x // scale]
            if x % 8 == 7:
                out.append(byte)
                byte = 0
        if size % 8:
            out.append(byte << (8 - size % 8))
    return bytes(out)


def c_array(data, indent="    ", per_line=16):
    rows = []
    for i in range(0, len(data), per_line):
        rows.append(indent + ", ".join(f"0x{b:02x}" for b in data[i : i + per_line]) + ",")
    return "\n".join(rows)


def img_dsc(name, cf, w, h, data):
    return (
        f"static const uint8_t {name}_map[] = {{\n{c_array(data)}\n}};\n"
        f"const lv_img_dsc_t {name} = {{\n"
        f"    .header.cf = {cf},\n"
        f"    .header.always_zero = 0,\n"
        f"    .header.reserved = 0,\n"
        f"    .header.w = {w},\n"
        f"    .header.h = {h},\n"
        f"    .data_size = {len(data)},\n"
        f"    .data = {name}_map,\n"
        f"}};\n\n"
    )


def icon_names():
    return sorted(p.stem for p in (DESIGN / "icons").glob("*.svg"))


def gen_icons():
    names = icon_names()
    if not names:
        raise SystemExit("no icons under design/icons")
    src = [BANNER, '#include "lvgl.h"\n\n']
    for name in names:
        grid = icon_grid(DESIGN / "icons" / f"{name}.svg")
        ident = name.replace("-", "_")
        for scale in SCALES:
            px = GRID * scale
            src.append(img_dsc(f"bm_icon_{ident}_{px}", "LV_IMG_CF_ALPHA_1BIT", px, px, alpha1(grid, scale)))
    (OUT / "bm_icons.c").write_text("".join(src))
    print(f"icons: {len(names)} glyphs x {len(SCALES)} scales")


# ---------------------------------------------------------------------------------------------------------
# Wordmark: the 480 x 65 display raster, shown 32 px tall, as an 8-bit alpha map recolored to ink at runtime
# ---------------------------------------------------------------------------------------------------------

WORDMARK_HEIGHT = 32


def gen_wordmark():
    from PIL import Image

    im = Image.open(DESIGN / "logos" / "bettermate-wordmark-display.png").convert("RGBA")
    alpha = im.getchannel("A")
    width = round(im.width * WORDMARK_HEIGHT / im.height)
    alpha = alpha.resize((width, WORDMARK_HEIGHT), Image.LANCZOS)
    # Drop the empty side margins so the object is no wider than the letters; it is centered by its box.
    left, _, right, _ = alpha.getbbox()
    alpha = alpha.crop((left, 0, right, WORDMARK_HEIGHT))
    src = [BANNER, '#include "lvgl.h"\n\n']
    src.append(img_dsc("bm_wordmark", "LV_IMG_CF_ALPHA_8BIT", alpha.width, alpha.height, alpha.tobytes()))
    (OUT / "bm_wordmark.c").write_text("".join(src))
    print(f"wordmark: {alpha.width} x {alpha.height}")


# ---------------------------------------------------------------------------------------------------------
# Fonts: static instances of the two variable faces -> LVGL bitmap fonts at the display's five type styles
# ---------------------------------------------------------------------------------------------------------

ASCII = "0x20-0x7E"
PUNCT = "0xB0,0xB7,0x2013,0x2014"  # degree, middle dot, en dash, em dash
LATIN1 = "0xA0-0xFF"  # profile names are typed by people: keep accented letters in the two sans styles

# name, source file, weight, size px, line height px (design tokens), glyphs, kerning
FONTS = [
    ("bm_font_sans_18", "SpaceGrotesk-Variable.woff2", 400, 18, 24, {"range": f"{ASCII},{LATIN1},0x2013,0x2014"}, True),
    ("bm_font_sans_24", "SpaceGrotesk-Variable.woff2", 600, 24, 28, {"range": f"{ASCII},{LATIN1},0x2013,0x2014"}, True),
    ("bm_font_mono_14", "JetBrainsMono-Variable.woff2", 500, 14, 18, {"range": f"{ASCII},{PUNCT}"}, False),
    ("bm_font_mono_28", "JetBrainsMono-Variable.woff2", 500, 28, 32, {"range": f"{ASCII},{PUNCT}"}, False),
    # The hero reading is only ever a number: time, temperature, weight, volume.
    ("bm_font_mono_64", "JetBrainsMono-Variable.woff2", 500, 64, 64, {"symbols": "0123456789:.-+%/ ", "range": PUNCT}, False),
]


def static_instance(source, weight, workdir):
    from fontTools.ttLib import TTFont
    from fontTools.varLib import instancer

    out = Path(workdir) / f"{Path(source).stem}-{weight}.ttf"
    if not out.exists():
        font = TTFont(DESIGN / "fonts" / source)
        instance = instancer.instantiateVariableFont(font, {"wght": weight})
        instance.flavor = None
        instance.save(out)
    return out


def css_line_box(ttf_path, size, line_height):
    """Where CSS puts the baseline in a line box of `line_height`: half-leading above the ascent."""
    from fontTools.ttLib import TTFont

    font = TTFont(ttf_path)
    upm = font["head"].unitsPerEm
    ascent = font["hhea"].ascent * size / upm
    descent = -font["hhea"].descent * size / upm
    baseline_from_top = (line_height - (ascent + descent)) / 2 + ascent
    return line_height, round(line_height - baseline_from_top)


def gen_fonts():
    conv = shlex.split(os.environ.get("LV_FONT_CONV", "npx --yes lv_font_conv@1.5.3"))
    with tempfile.TemporaryDirectory() as workdir:
        for name, source, weight, size, line_height, glyphs, kerning in FONTS:
            ttf = static_instance(source, weight, workdir)
            out = OUT / f"{name}.c"
            cmd = conv + ["--font", str(ttf)]
            if "range" in glyphs:
                cmd += ["-r", glyphs["range"]]
            if "symbols" in glyphs:
                cmd += ["--symbols", glyphs["symbols"]]
            cmd += ["--size", str(size), "--bpp", "4", "--format", "lvgl", "--lv-include", "lvgl.h"]
            cmd += ["--lv-font-name", name, "-o", str(out)]
            if not kerning:
                cmd.append("--no-kerning")
            subprocess.run(cmd, check=True)

            # lv_font_conv sizes the line to the tallest glyph. The design sets an explicit line height per
            # type style, so pin the line box to it the way CSS would lay the same text out.
            line, base = css_line_box(ttf, size, line_height)
            text = out.read_text()
            text, n1 = re.subn(r"\.line_height = \d+,", f".line_height = {line},", text)
            text, n2 = re.subn(r"\.base_line = -?\d+,", f".base_line = {base},", text)
            if n1 != 1 or n2 != 1:
                raise SystemExit(f"{name}: could not pin the line box, lv_font_conv output changed shape")
            # The converter records its full command line, temp paths included; keep the file reproducible.
            text = re.sub(r" \* Opts: .*\n", f" * Opts: {Path(source).name} wght {weight}, {size} px, bpp 4\n", text)
            out.write_text(BANNER + text)
            print(f"font: {name} ({Path(source).stem} {weight}, {size}/{line_height} px) {out.stat().st_size // 1024} KB of C")


# ---------------------------------------------------------------------------------------------------------
# Declarations shared by the generated assets
# ---------------------------------------------------------------------------------------------------------


def gen_header():
    lines = [BANNER, "#pragma once\n\n", '#include "lvgl.h"\n\n', "#ifdef __cplusplus\n", 'extern "C" {\n', "#endif\n\n"]
    lines.append("// Type styles of the round display (design/tokens.json, group \"Round display\").\n")
    for name, source, weight, size, line_height, _, _ in FONTS:
        lines.append(f"LV_FONT_DECLARE({name}) // {Path(source).stem.split('-')[0]} {weight}, {size}/{line_height} px\n")
    lines.append("\n// The wordmark, 32 px tall. Alpha only: set img_recolor to ink.\n")
    lines.append("LV_IMG_DECLARE(bm_wordmark)\n")
    lines.append("\n// Pixel glyphs at exact 1x, 2x and 3x of the 24-unit grid. Alpha only: set img_recolor.\n")
    for name in icon_names():
        ident = name.replace("-", "_")
        lines.append("".join(f"LV_IMG_DECLARE(bm_icon_{ident}_{GRID * s}) " for s in SCALES).rstrip() + "\n")
    lines += ["\n#ifdef __cplusplus\n", "}\n", "#endif\n"]
    (OUT / "bm_assets.h").write_text("".join(lines))


STEPS = {"tokens": gen_tokens, "icons": gen_icons, "wordmark": gen_wordmark, "fonts": gen_fonts}


def main():
    wanted = sys.argv[1:] or list(STEPS)
    unknown = [w for w in wanted if w not in STEPS]
    if unknown:
        raise SystemExit(f"unknown step(s) {unknown}; choose from {list(STEPS)}")
    OUT.mkdir(parents=True, exist_ok=True)
    for step in wanted:
        STEPS[step]()
    gen_header()


if __name__ == "__main__":
    main()
