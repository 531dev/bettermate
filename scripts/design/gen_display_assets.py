#!/usr/bin/env python3
"""Generate the round display's design assets from design/ into src/display/ui/bettermate/gen/.

    scripts/design/gen_display_assets.py            # everything
    scripts/design/gen_display_assets.py tokens     # one of: tokens icons fonts

Sources (an unchanged copy of the BetterMate v2 design system, see design/reference/SOURCE.md):
    design/tokens.json                 colors per theme, sizes, ring geometry, frame counts, type styles
    design/icons.json                  53 stroke glyphs on a 24-unit grid
    design/fonts/*-Variable.woff2      Funnel Display and Geist Mono

The output is committed, so a firmware build needs none of this tooling. To regenerate you need Python with
fonttools, brotli and Pillow, rsvg-convert (librsvg) for the icons, and Node for lv_font_conv (override the
command with LV_FONT_CONV, default "npx --yes lv_font_conv@1.5.3").
"""

import io
import json
import os
import re
import shlex
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DESIGN = ROOT / "design"
OUT = ROOT / "src" / "display" / "ui" / "bettermate" / "gen"
BANNER = "// Generated by scripts/design/gen_display_assets.py. Do not edit; change design/ and regenerate.\n"

# The display ships Display black (the amoled theme) on every panel; Light remains a setting.
THEMES = ["light", "amoled"]

# ---------------------------------------------------------------------------------------------------------
# Tokens
# ---------------------------------------------------------------------------------------------------------


def camel(name):
    parts = re.split(r"[-_.]", name)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def upper_snake(name):
    return re.sub(r"[-.]", "_", name).upper()


def load_tokens():
    return json.loads((DESIGN / "tokens.json").read_text())


def resolve_color(tokens_by_name, name, theme, seen=()):
    """Follow "{alias}" references and theme fallback (a missing theme inherits the first one)."""
    if name in seen:
        raise SystemExit(f"alias loop at color token {name}")
    value = tokens_by_name[name]["value"]
    if isinstance(value, dict):
        value = value.get(theme, next(iter(value.values())))
    alias = re.fullmatch(r"\{([^}]+)\}", value)
    if alias:
        return resolve_color(tokens_by_name, alias.group(1), theme, seen + (name,))
    return value


def display_styles(tokens):
    group = next(g for g in tokens["type"]["groups"] if g["name"] == "Round display")
    return {s["name"]: s for s in group["styles"]}


def tracking(style):
    """Letter spacing in whole pixels: LVGL has no fractional tracking."""
    em = float(str(style.get("letterSpacing", "0em")).replace("em", ""))
    return round(em * int(style["fontSize"].replace("px", "")))


def gen_tokens():
    tokens = load_tokens()
    colors = tokens["color"]["tokens"]
    by_name = {t["name"]: t for t in colors}

    fields = []
    for t in colors:
        hexes = [resolve_color(by_name, t["name"], theme) for theme in THEMES]
        # The display never composites: tokens with an alpha channel (scrim) are web-only.
        if not all(re.fullmatch(r"#[0-9a-fA-F]{6}", h) for h in hexes):
            continue
        fields.append((camel(t["name"]), hexes))

    lines = [BANNER, "#pragma once\n", "#include <cstdint>\n", "\nnamespace bm::tokens {\n"]
    lines.append("\n// One 0xRRGGBB value per color token; design/tokens.json says what each one is for.\n")
    lines.append("struct Palette {\n")
    for name, _ in fields:
        lines.append(f"    uint32_t {name};\n")
    lines.append("};\n")
    for i, theme in enumerate(THEMES):
        lines.append(f"\ninline constexpr Palette {theme.upper()} = {{\n")
        for name, hexes in fields:
            lines.append(f"    0x{hexes[i][1:].lower()}, // {name}\n")
        lines.append("};\n")

    def family(key, comment, pattern=r"(\d+)(?:px)?"):
        lines.append(f"\n// {comment}\n")
        for t in tokens[key]["tokens"]:
            m = re.fullmatch(pattern, str(t["value"]))
            if not m:
                continue
            # Arduino.h defines DISPLAY as a macro; keep the token source unchanged but avoid that C++ name.
            name = "DISPLAY_SIZE" if t["name"] == "display" else upper_snake(t["name"])
            lines.append(f"inline constexpr int {name} = {m.group(1)};\n")

    family("radius", "Corner radii, px (radius-pill is LV_RADIUS_CIRCLE on the display)")
    family("size", "Sizes, px")
    family("ring", "The tick ring, px from the centre of the panel; ring-pitch is in degrees")
    family("frame", "Motion, in panel frames (design/reference/motion.md)")

    lines.append("\n// Letter spacing of the display's type styles, px\n")
    for name, style in display_styles(tokens).items():
        lines.append(f"inline constexpr int TRACKING_{upper_snake(name)} = {tracking(style)};\n")
    lines.append("\n} // namespace bm::tokens\n")
    (OUT / "bm_tokens.h").write_text("".join(lines))
    print(f"tokens: {len(fields)} colors x {len(THEMES)} themes")


# ---------------------------------------------------------------------------------------------------------
# Icons: 24-unit stroke glyphs -> 8-bit alpha maps at the sizes the display draws them
# ---------------------------------------------------------------------------------------------------------

# LV_IMG_CF_ALPHA_8BIT is the one alpha format LVGL 8 blends straight from flash as a mask; the packed 1/2/4-bit
# formats go through a per-line decoder. Unused glyphs cost nothing: the linker drops them.
ICONS = {
    24: ["chevron-right"],
    28: ["minus", "plus", "triangle-alert", "download", "chevron-left", "chevron-right", "pencil", "check", "x", "scale"],
    32: ["chevron-up", "chevron-down"],
    36: ["coffee", "wind", "droplet", "bean", "info", "power"],
}


def c_array(data, indent="    ", per_line=20):
    rows = []
    for i in range(0, len(data), per_line):
        rows.append(indent + ", ".join(f"0x{b:02x}" for b in data[i : i + per_line]) + ",")
    return "\n".join(rows)


def img_dsc(name, w, h, data):
    return (
        f"static const uint8_t {name}_map[] = {{\n{c_array(data)}\n}};\n"
        f"const lv_img_dsc_t {name} = {{\n"
        f"    .header.cf = LV_IMG_CF_ALPHA_8BIT,\n"
        f"    .header.always_zero = 0,\n"
        f"    .header.reserved = 0,\n"
        f"    .header.w = {w},\n"
        f"    .header.h = {h},\n"
        f"    .data_size = {len(data)},\n"
        f"    .data = {name}_map,\n"
        f"}};\n\n"
    )


def icon_ident(name, size):
    return f"bm_icon_{name.replace('-', '_')}_{size}"


def gen_icons():
    from PIL import Image

    rsvg = shutil.which("rsvg-convert")
    if not rsvg:
        raise SystemExit("rsvg-convert not found (brew install librsvg)")
    spec = json.loads((DESIGN / "icons.json").read_text())
    src = [BANNER, '#include "lvgl.h"\n\n']
    count = 0
    for size, names in ICONS.items():
        for name in names:
            if name not in spec["paths"]:
                raise SystemExit(f"icon {name} is not in design/icons.json")
            svg = (
                f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {spec["grid"]} {spec["grid"]}" width="{size}" '
                f'height="{size}" fill="none" stroke="#fff" stroke-width="{spec["stroke"]}" '
                f'stroke-linecap="{spec["cap"]}" stroke-linejoin="{spec["join"]}"><path d="{spec["paths"][name]}"/></svg>'
            )
            png = subprocess.run([rsvg, "-w", str(size), "-h", str(size), "-f", "png"], input=svg.encode(), capture_output=True, check=True)
            alpha = Image.open(io.BytesIO(png.stdout)).convert("RGBA").getchannel("A")
            if alpha.size != (size, size):
                raise SystemExit(f"{name}: rendered {alpha.size}, expected {size} px")
            src.append(img_dsc(icon_ident(name, size), size, size, alpha.tobytes()))
            count += 1
    (OUT / "bm_icons.c").write_text("".join(src))
    print(f"icons: {count} alpha maps")


# ---------------------------------------------------------------------------------------------------------
# Fonts: static instances of the two variable faces -> LVGL bitmap fonts for the display's seven type styles
# ---------------------------------------------------------------------------------------------------------

DIGITS = "0123456789"
UPPER = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
ASCII = "".join(chr(c) for c in range(0x20, 0x7F))
PUNCT = "".join(chr(c) for c in range(0x20, 0x7F) if not chr(c).isalnum())
DEGREE, MIDDOT, ELLIPSIS = "°", "·", "…"
# Profile and phase names are typed by people: the text styles carry the Latin-1 Supplement (U+00A0 to U+00FF,
# which holds degree and middle dot) and the label its capitals, for the Adjust title (Round display, Fonts).
LATIN1 = "".join(chr(c) for c in range(0xA0, 0x100))
LATIN1_UPPER = "".join(chr(c) for c in range(0xC0, 0xDF))

SANS, MONO = "FunnelDisplay-Variable.woff2", "GeistMono-Variable.woff2"

# C name, token style, source, glyphs, kerning. Size and weight come from the token style. Numerals stay
# unkerned: Funnel Display's figures are tabular as drawn, so a changing digit never moves its neighbours.
FONTS = [
    ("bm_font_hero", "screen-hero", SANS, DIGITS + ":.- " + DEGREE, False),
    ("bm_font_hero_sm", "screen-hero-sm", SANS, DIGITS + ":.- " + DEGREE, False),
    ("bm_font_value", "screen-value", SANS, ASCII + LATIN1 + ELLIPSIS, False),
    ("bm_font_title", "screen-title", SANS, ASCII + LATIN1 + ELLIPSIS, True),
    ("bm_font_body", "screen-body", SANS, ASCII + LATIN1 + ELLIPSIS, True),
    ("bm_font_label", "screen-label", MONO, UPPER + DIGITS + PUNCT + DEGREE + MIDDOT + LATIN1_UPPER + ELLIPSIS, False),
    ("bm_font_button", "screen-button", MONO, UPPER + " &", False),
]


def static_instance(source, weight, workdir):
    from fontTools.ttLib import TTFont
    from fontTools.varLib import instancer

    out = Path(workdir) / f"{Path(source).stem}-{weight}.ttf"
    if not out.exists():
        font = TTFont(DESIGN / "fonts" / source)
        instance = instancer.instantiateVariableFont(font, {"wght": weight})
        instance.flavor = None
        instance.save(out)
    return out


def gen_fonts():
    from fontTools.ttLib import TTFont

    styles = display_styles(load_tokens())
    conv = shlex.split(os.environ.get("LV_FONT_CONV", "npx --yes lv_font_conv@1.5.3"))
    with tempfile.TemporaryDirectory() as workdir:
        for name, style_name, source, glyphs, kerning in FONTS:
            style = styles[style_name]
            size, weight = int(style["fontSize"].replace("px", "")), int(style["fontWeight"])
            ttf = static_instance(source, weight, workdir)
            cmap = TTFont(ttf).getBestCmap()
            have = sorted({c for c in glyphs if ord(c) in cmap})
            missing = sorted(set(glyphs) - set(have))
            ranges = ",".join(f"0x{ord(c):X}" for c in have)
            out = OUT / f"{name}.c"
            # Uncompressed 4 bpp: a compressed glyph is unpacked on every draw, and flash is not what is scarce.
            cmd = conv + ["--font", str(ttf), "-r", ranges, "--size", str(size), "--bpp", "4", "--no-compress"]
            cmd += ["--format", "lvgl", "--lv-include", "lvgl.h", "--lv-font-name", name, "-o", str(out)]
            if not kerning:
                cmd.append("--no-kerning")
            subprocess.run(cmd, check=True)
            text = out.read_text()
            # The converter records its full command line, temp paths included; keep the file reproducible.
            text = re.sub(r" \* Opts: .*\n", f" * Opts: {Path(source).name} wght {weight}, {size} px, bpp 4, {len(have)} glyphs\n", text)
            out.write_text(BANNER + text)
            note = f", not in the face: {''.join(missing)!r}" if missing else ""
            print(f"font: {name} ({Path(source).stem.split('-')[0]} {weight}, {size} px, {len(have)} glyphs) {out.stat().st_size // 1024} KB of C{note}")


# ---------------------------------------------------------------------------------------------------------
# Declarations shared by the generated assets
# ---------------------------------------------------------------------------------------------------------


def gen_header():
    styles = display_styles(load_tokens())
    lines = [BANNER, "#pragma once\n\n", '#include "lvgl.h"\n\n', "#ifdef __cplusplus\n", 'extern "C" {\n', "#endif\n\n"]
    lines.append('// Type styles of the round display (design/tokens.json, group "Round display").\n')
    for name, style_name, source, _, _ in FONTS:
        style = styles[style_name]
        face = "Funnel Display" if source == SANS else "Geist Mono"
        lines.append(f"LV_FONT_DECLARE({name}) // {style_name}: {face} {style['fontWeight']}, {style['fontSize']}\n")
    lines.append("\n// Stroke glyphs as 8-bit alpha maps, named by size in px. Alpha only: the style's img_recolor colors them.\n")
    for size, names in ICONS.items():
        for name in names:
            lines.append(f"LV_IMG_DECLARE({icon_ident(name, size)})\n")
    lines += ["\n#ifdef __cplusplus\n", "}\n", "#endif\n"]
    (OUT / "bm_assets.h").write_text("".join(lines))


STEPS = {"tokens": gen_tokens, "icons": gen_icons, "fonts": gen_fonts}


def main():
    wanted = sys.argv[1:] or list(STEPS)
    unknown = [w for w in wanted if w not in STEPS]
    if unknown:
        raise SystemExit(f"unknown step(s) {unknown}; choose from {list(STEPS)}")
    OUT.mkdir(parents=True, exist_ok=True)
    for step in wanted:
        STEPS[step]()
    gen_header()


if __name__ == "__main__":
    main()
