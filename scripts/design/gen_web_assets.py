#!/usr/bin/env python3
"""Generate the web UI's design assets from the immutable sources in design/.

From design/tokens.json, design/icons.json, design/fonts/ and design/logos/ this writes:

  web/src/design/tokens.css      the web's tokens as CSS custom properties, Light and Dark
  web/src/design/iconPaths.js    the stroke glyphs
  web/public/fonts/              the variable fonts and their licence, and nothing else
  web/public/bettermate-wordmark.svg, bettermate-wordmark-inverse.svg
  web/public/bettermate.svg, bettermate-192.png, bettermate-512.png
                                 the coffee glyph in primary on surface-0
  web/index.html, web/public/app.webmanifest
                                 the page ground (surface-0), stamped in place

Needs Pillow and rsvg-convert. Run it after design/ changes:

    python3 scripts/design/gen_web_assets.py
"""

import io
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys

from PIL import Image


ROOT = Path(__file__).resolve().parents[2]
DESIGN = ROOT / "design"
WEB = ROOT / "web"
PUBLIC = WEB / "public"
GENERATED = WEB / "src/design"

HEADER = "Generated by scripts/design/gen_web_assets.py from design/{source}. Do not edit."
# The web's themes. `amoled` is the round display's and stays out of the web bundle.
THEMES = {"light": ":root,\n[data-theme='light']", "dark": "[data-theme='dark']"}
# Token groups the web recipes read, besides colors and the two font families.
GROUPS = ["spacing", "radius", "size", "border", "opacity", "layer", "duration", "easing"]
WORDMARKS = ["bettermate-wordmark.svg", "bettermate-wordmark-inverse.svg"]
MARK_GLYPH = "coffee"
PRINT_WIDTH, TAB_WIDTH = 100, 2  # web/.prettierrc, so `npm run format` leaves the output alone


def css_value(value, theme=None):
    """A token value as CSS: the theme's color, or `{alias}` as `var(--alias)`."""
    if isinstance(value, dict):
        return value[theme]
    return re.sub(r"\{([^}]+)\}", r"var(--\1)", value)


def color(tokens, name, theme="light"):
    token = next(t for t in tokens["color"]["tokens"] if t["name"] == name)
    return css_value(token["value"], theme)


def write_tokens_css(tokens):
    css = [f"/* {HEADER.format(source='tokens.json')} */"]
    for theme, selector in THEMES.items():
        css.append(f"{selector} {{")
        css.extend(f"  --{t['name']}: {css_value(t['value'], theme)};" for t in tokens["color"]["tokens"])
        css.append("}")
    css.append(":root {")
    for name, stack in tokens["type"]["families"].items():
        css.append(f"  --font-{name}: {stack.replace(chr(34), chr(39))};")
    for group in GROUPS:
        css.extend(f"  --{t['name']}: {css_value(t['value'])};" for t in tokens[group]["tokens"])
    css.append("}")
    (GENERATED / "tokens.css").write_text("\n".join(css) + "\n")


def write_icon_paths(icons):
    lines = [
        f"// {HEADER.format(source='icons.json')}",
        f"// {len(icons['paths'])} stroke glyphs on a {icons['grid']} unit grid: {icons['stroke']} stroke,"
        f" {icons['cap']} caps and joins, drawn in currentColor.",
        "export const iconPaths = {",
    ]
    for name, path in icons["paths"].items():
        key = name if name.isidentifier() else f"'{name}'"
        entry = f"  {key}: '{path}',"
        # Prettier moves a value that overflows the line under its key, unless the key is too
        # short for the move to gain anything (under tab width + 3 characters).
        wraps = len(entry) > PRINT_WIDTH and len(key) >= TAB_WIDTH + 3
        lines.extend([f"  {key}:", f"    '{path}',"] if wraps else [entry])
    lines.append("};")
    (GENERATED / "iconPaths.js").write_text("\n".join(lines) + "\n")


def sync_fonts(tokens):
    """Mirror design/fonts: copy what is there, remove what no longer is."""
    target = PUBLIC / "fonts"
    target.mkdir(parents=True, exist_ok=True)
    sources = {f.name: f for f in (DESIGN / "fonts").iterdir() if f.is_file() and not f.name.startswith(".")}
    for font in tokens["type"]["fonts"]:
        if Path(font["file"]).name not in sources:
            sys.exit(f"design/{font['file']} is named in tokens.json but missing")
    for stale in target.iterdir():
        if stale.name not in sources:
            stale.unlink()
    for name, source in sources.items():
        shutil.copyfile(source, target / name)
    return sorted(sources)


def mark_svg(icons, glyph, ground, ink, canvas, radius=0):
    """The glyph centred on a square ground; `canvas` is the square's side in grid units."""
    inset = (canvas - icons["grid"]) / 2
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {canvas} {canvas}">'
        f'<rect width="{canvas}" height="{canvas}" rx="{radius}" fill="{ground}"/>'
        f'<path transform="translate({inset:g} {inset:g})" d="{icons["paths"][glyph]}" fill="none" stroke="{ink}"'
        f' stroke-width="{icons["stroke"]}" stroke-linecap="{icons["cap"]}" stroke-linejoin="{icons["join"]}"/>'
        "</svg>\n"
    )


def write_marks(tokens, icons):
    ground, ink = color(tokens, "surface-0"), color(tokens, "primary")
    # Browser tab: a tight, rounded square so the 1.6 stroke stays visible at 16 px.
    (PUBLIC / "bettermate.svg").write_text(mark_svg(icons, MARK_GLYPH, ground, ink, canvas=28, radius=6))
    # Home screen: full bleed, with the glyph inside the maskable safe zone.
    app_icon = mark_svg(icons, MARK_GLYPH, ground, ink, canvas=32).encode()
    rsvg = shutil.which("rsvg-convert") or "/opt/homebrew/bin/rsvg-convert"
    for size in [192, 512]:
        png = subprocess.run(
            [rsvg, "--width", str(size), "--height", str(size)], input=app_icon, capture_output=True, check=True
        ).stdout
        # Two flat colors and their blends: a small palette loses nothing and keeps the files light.
        image = Image.open(io.BytesIO(png)).convert("RGB").quantize(colors=32, dither=Image.Dither.NONE)
        image.save(PUBLIC / f"bettermate-{size}.png", optimize=True)


def stamp(path, replacements):
    """Replace values in a hand-written file, and fail loudly if its markup moved."""
    text = path.read_text()
    for pattern, value in replacements:
        text, count = re.subn(pattern, lambda match: match.group(1) + value + match.group(2), text)
        if count != 1:
            sys.exit(f"{path.relative_to(ROOT)}: expected one match for {pattern!r}, found {count}")
    path.write_text(text)


def stamp_ground(tokens):
    light, dark = color(tokens, "surface-0", "light"), color(tokens, "surface-0", "dark")
    hexa = r"#[0-9a-fA-F]{6}"
    stamp(
        PUBLIC / "app.webmanifest",
        [(rf'("theme_color": "){hexa}(")', light), (rf'("background_color": "){hexa}(")', light)],
    )
    stamp(
        WEB / "index.html",
        [
            (rf'(<meta name="theme-color" content="){hexa}(")', light),
            (rf"(html \{{\s*background: ){hexa}(;)", light),
            (rf"(html\[data-theme='dark'\] \{{\s*background: ){hexa}(;)", dark),
        ],
    )


def check_font_references(fonts):
    """Fonts are declared by hand in two places; make sure neither fell behind design/fonts."""
    for name in (n for n in fonts if n.endswith(".woff2")):
        for file in [WEB / "src/style.css", WEB / "index.html"]:
            if f"/fonts/{name}" not in file.read_text():
                sys.exit(f"{file.relative_to(ROOT)} does not load /fonts/{name}")


def main():
    tokens = json.loads((DESIGN / "tokens.json").read_text())
    icons = json.loads((DESIGN / "icons.json").read_text())
    GENERATED.mkdir(parents=True, exist_ok=True)

    write_tokens_css(tokens)
    write_icon_paths(icons)
    fonts = sync_fonts(tokens)
    for name in WORDMARKS:
        shutil.copyfile(DESIGN / "logos" / name, PUBLIC / name)
    write_marks(tokens, icons)
    stamp_ground(tokens)
    check_font_references(fonts)
    print(
        f"Generated tokens.css ({len(tokens['color']['tokens'])} colors in {len(THEMES)} themes), "
        f"{len(icons['paths'])} icons, {len(fonts)} font files, the wordmarks and the BetterMate marks."
    )


if __name__ == "__main__":
    main()
