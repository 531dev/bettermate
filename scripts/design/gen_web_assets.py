#!/usr/bin/env python3
"""Copy web fonts/marks and generate pixel paths and CSS themes from the immutable design sources."""

import json
from pathlib import Path
import re
import shutil

from PIL import Image
from gen_display_assets import icon_grid


ROOT = Path(__file__).resolve().parents[2]
DESIGN = ROOT / "design"
PUBLIC = ROOT / "web/public"
GENERATED = ROOT / "web/src/design"


def main():
    GENERATED.mkdir(parents=True, exist_ok=True)
    (PUBLIC / "fonts").mkdir(exist_ok=True)
    for file in (DESIGN / "fonts").iterdir():
        shutil.copy2(file, PUBLIC / "fonts" / file.name)
    for name in ["bettermate-wordmark.svg", "bettermate-wordmark-inverse.svg"]:
        shutil.copy2(DESIGN / "logos" / name, PUBLIC / name)
    shutil.copy2(DESIGN / "icons/coffee.svg", PUBLIC / "bettermate.svg")
    grid = icon_grid(DESIGN / "icons/coffee.svg")
    mark = Image.new("RGB", (24, 24), "#e9e9e9")
    for y, row in enumerate(grid):
        for x, lit in enumerate(row):
            if lit:
                mark.putpixel((x, y), (42, 59, 234))
    for size in [192, 512]:
        # Integer pixel runs; retain hard edges when adding the PWA canvas.
        scale = size // 32
        icon = mark.resize((24 * scale, 24 * scale), Image.Resampling.NEAREST)
        canvas = Image.new("RGB", (size, size), "#e9e9e9")
        canvas.paste(icon, ((size - icon.width) // 2, (size - icon.height) // 2))
        canvas.save(PUBLIC / f"bettermate-{size}.png")

    paths = {}
    for file in sorted((DESIGN / "icons").glob("*.svg")):
        paths[file.stem] = "".join(re.findall(r'\bd="([^"]+)"', file.read_text()))
    (GENERATED / "iconPaths.js").write_text(
        "// Generated by scripts/design/gen_web_assets.py; edit design sources instead.\n"
        + "export const iconPaths = {\n"
        + "\n".join(f"  {name if name.isidentifier() else repr(name)}: {json.dumps(value)}," for name, value in paths.items())
        + "\n};\n"
    )

    tokens = json.loads((DESIGN / "tokens.json").read_text())
    mapping = {
        "base-100": "surface-1", "base-200": "surface-0", "base-300": "line", "base-content": "ink",
        "primary": "primary", "primary-content": "on-primary", "secondary": "heat", "secondary-content": "on-heat",
        "accent": "flow", "accent-content": "surface-2", "neutral": "ink", "neutral-content": "surface-0",
        "info": "primary-soft", "info-content": "primary", "success": "success-soft", "success-content": "success",
        "warning": "warning-soft", "warning-content": "warning", "error": "danger-soft", "error-content": "danger",
    }
    css = ["/* Generated by scripts/design/gen_web_assets.py; do not edit. */"]
    for theme in ["light", "dark"]:
        css.extend([
            '@plugin "daisyui/theme" {', f"  name: '{theme}';", f"  default: {'true' if theme == 'light' else 'false'};",
            f"  prefersdark: {'true' if theme == 'dark' else 'false'};", f"  color-scheme: '{theme}';",
        ])
        for token in tokens["color"]["tokens"]:
            value = token["value"]
            value = value[theme] if isinstance(value, dict) else re.sub(r"\{([^}]+)\}", r"var(--\1)", value)
            css.append(f"  --{token['name']}: {value};")
        for name, token in mapping.items():
            css.append(f"  --color-{name}: var(--{token});")
        css.extend([
            "  --radius-selector: 9999px;", "  --radius-field: 12px;", "  --radius-box: 24px;",
            "  --size-selector: 0.25rem;", "  --size-field: 0.25rem;", "  --border: 1px;",
            "  --depth: 0;", "  --noise: 0;", "}", "",
        ])
    (GENERATED / "themes.css").write_text("\n".join(css))
    print(f"Generated {len(paths)} shared pixel icons, two themes, fonts and BetterMate marks.")


if __name__ == "__main__":
    main()
