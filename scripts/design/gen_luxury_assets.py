#!/usr/bin/env python3
"""Generate the minimal-luxury Jost display fonts from the bundled OFL source.

Keeps the original design assets intact. Generated C files are committed, so
normal firmware builds do not need the font converter or Python dependencies.
"""
import gen_display_assets as assets


def static_instance(source, weight, workdir):
    path = original_instance(source, weight, workdir)
    if source == "Jost-Variable.woff2":
        # Preserve the recipe arrow if a font source omits it. Add a simple
        # arrow as an original outline instead of pulling in another font.
        from fontTools.ttLib import TTFont
        from fontTools.pens.ttGlyphPen import TTGlyphPen
        font = TTFont(path)
        # LVGL has no OpenType shaping. Resolve Jost's tabular figures into
        # the cmap so clocks and telemetry retain a fixed width as they update.
        for record in font["GSUB"].table.FeatureList.FeatureRecord:
            if record.FeatureTag == "tnum":
                for index in record.Feature.LookupListIndex:
                    for subtable in font["GSUB"].table.LookupList.Lookup[index].SubTable:
                        for table in font["cmap"].tables:
                            if table.isUnicode():
                                for codepoint, glyph in table.cmap.items():
                                    table.cmap[codepoint] = subtable.mapping.get(glyph, glyph)
        if 0x2192 not in font.getBestCmap():
            pen = TTGlyphPen(None)
            for points in [((40, 280), (470, 280), (470, 340), (40, 340)),
                           ((330, 130), (390, 130), (570, 310), (390, 490), (330, 490), (510, 310))]:
                pen.moveTo(points[0])
                for point in points[1:]:
                    pen.lineTo(point)
                pen.closePath()
            font.setGlyphOrder(font.getGlyphOrder() + ["bm_recipe_arrow"])
            font["glyf"]["bm_recipe_arrow"] = pen.glyph()
            font["hmtx"].metrics["bm_recipe_arrow"] = (600, 40)
            for table in font["cmap"].tables:
                if table.isUnicode():
                    table.cmap[0x2192] = "bm_recipe_arrow"
        font.save(path)
    return path


original_instance = assets.static_instance
assets.static_instance = static_instance


FONTS = [
    ("bm_luxury_picker", "Jost-Variable.woff2", 300, 60, 72,
     {"symbols": "BrewGrindSteamWaterInfo "}, False),
    ("bm_luxury_brew", "Jost-Variable.woff2", 300, 144, 158,
     {"symbols": "0123456789- "}, False),
    ("bm_luxury_profile", "Jost-Variable.woff2", 300, 42, 52,
     {"range": f"{assets.ASCII},{assets.LATIN1},0x2013,0x2014"}, True),
    ("bm_luxury_recipe", "Jost-Variable.woff2", 300, 20, 26,
     {"range": f"{assets.ASCII},{assets.LATIN1},0x2013,0x2014"}, True),
    ("bm_luxury_detail", "Jost-Variable.woff2", 400, 14, 20,
     {"range": f"{assets.ASCII},{assets.LATIN1},0x2013,0x2014"}, True),
    ("bm_luxury_clock", "Jost-Variable.woff2", 300, 112, 120,
     {"symbols": "0123456789:- "}, False),
    ("bm_luxury_reading", "Jost-Variable.woff2", 300, 72, 82,
     {"symbols": "0123456789:.- "}, False),
    ("bm_luxury_mode", "Jost-Variable.woff2", 300, 30, 38,
     {"range": f"{assets.ASCII},{assets.LATIN1},0x2013,0x2014"}, True),
    ("bm_luxury_body", "Jost-Variable.woff2", 400, 18, 24,
     {"range": f"{assets.ASCII},{assets.LATIN1},0x2013,0x2014"}, True),
    ("bm_luxury_label", "Jost-Variable.woff2", 400, 12, 18,
     {"range": f"{assets.ASCII},{assets.PUNCT},0x2192"}, False),
]


if __name__ == "__main__":
    assets.FONTS = FONTS
    assets.BANNER = "// Generated by scripts/design/gen_luxury_assets.py. Do not edit; regenerate from bundled fonts.\n"
    assets.OUT.mkdir(parents=True, exist_ok=True)
    assets.gen_fonts()
    header = ['// Generated by scripts/design/gen_luxury_assets.py.\n',
              '#pragma once\n#include "lvgl.h"\n',
              '#ifdef __cplusplus\nextern "C" {\n#endif\n']
    header += [f"LV_FONT_DECLARE({font[0]})\n" for font in FONTS]
    header += ['#ifdef __cplusplus\n}\n#endif\n']
    (assets.OUT / "bm_luxury_assets.h").write_text("".join(header))
